#include<stdio.h>
int main()
{
	float  H,P,V; //H-height,P-power,V-flow rate 
        printf("Enter the height in meters-m :");
	scanf("%f", &H);
	printf("Enter the flow rate of water in m^3/s:");
	scanf("%f", &V);
	P = (0.9)*(1000*V*9.8*H)/1000000.0;//dividing by 10^6 is to convert it to megawatts
	printf("Power generated by the hydroelectric dam is %.2f MegaWatts\n",P);
        return 0;

}


